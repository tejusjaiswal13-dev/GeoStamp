@Composable
private fun SupportTopicItem(text: String) {
    Text(
        text = text,
        fontSize = 11.sp,
        fontWeight = FontWeight.Medium,
        color = MaterialTheme.colorScheme.onSurfaceVariant
    )
}

private fun sendSupportEmail(context: Context, emailAddress: String) {
    val intent = Intent(Intent.ACTION_SENDTO).apply {
        data = Uri.parse("mailto:$emailAddress?subject=GeoStamp%20Support%20%26%20Feedback")
        addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
    }
    try {
        context.startActivity(Intent.createChooser(intent, "Send Email via"))
    } catch (e: Exception) {
        Toast.makeText(context, "No email app found on device", Toast.LENGTH_SHORT).show()
    }
}
